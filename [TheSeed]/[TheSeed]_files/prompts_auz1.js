const chatRounds = () => clamp(Math.round(+SET.aiRounds || 10), 1, 20);
// log: [{ r: 'p' | 'h', t }], the last entry is what the player just said
function buildChatMessages(id, log) {
  const lines = log.filter(q => (q.r === 'p' || q.r === 'h') && q.t), cur = lines[lines.length - 1];
  let hist = lines.slice(0, -1).slice(-chatRounds() * 2); while (hist.length && hist[0].r !== 'p') hist.shift();
  const msgs = hist.map(q => ({ role: q.r === 'p' ? 'user' : 'assistant', content: q.t }));
  // the platform takes no system role: the head rides on the first user turn
  msgs.push({ role: 'user', content: cur.t }); msgs[0] = { role: 'user', content: promptHead('chat', id) + '\n\n' + (SET.name || '?') + '：' + msgs[0].content }; return msgs;
}
